function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();

  useEffect(() => {
    const { data: sub } = supabase.auth.onAuthStateChange((_event: string) => {
      if (_event !== "SIGNED_IN" && _event !== "SIGNED_OUT" && _event !== "USER_UPDATED") return;
      router.invalidate();
      if (_event !== "SIGNED_OUT") queryClient.invalidateQueries();
    });
    return () => sub.subscription.unsubscribe();
  }, [router, queryClient]);

  return (
    <QueryClientProvider client={queryClient}>
      <div className="min-h-screen flex flex-col">
        <SiteHeader />
        <main className="flex-1">
          <Outlet />
        </main>
      </div>
      <Toaster theme="dark" position="top-center" />
    </QueryClientProvider>
  );
}
